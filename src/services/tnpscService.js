    const totalAttempts  = list.length
    const totalQuestions = list.reduce((s, a) => s + ((a.correct_count ?? 0) + (a.incorrect_count ?? 0) + (a.unanswered_count ?? 0)), 0)
    const totalCorrect   = list.reduce((s, a) => s + (a.correct_count   ?? 0), 0)
