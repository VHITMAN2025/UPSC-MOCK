// ─── Syllabus ────────────────────────────────────────────────────────────────
export const syllabusService = {
  async getExams() {
    const { data, error } = await supabase.from('syllabus_exams').select('*')
    if (error) throw error
    return data ?? []
  },

  async getUnitsWithTopics(examName) {
    const { data: exam } = await supabase
      .from('syllabus_exams').select('id').eq('exam_name', examName).maybeSingle()
    if (!exam) return []

    const { data: units, error } = await supabase
      .from('syllabus_units')
      .select('*, syllabus_topics(*)')
      .eq('exam_id', exam.id)
      .order('unit_number')
    if (error) throw error

    // Deduplicate units by unit_number and merge their topics to prevent duplicate display
    const unitMap = new Map()
    for (const u of (units || [])) {
      const key = u.unit_number || u.unit_name
      if (!unitMap.has(key)) {
        unitMap.set(key, { ...u, syllabus_topics: [...(u.syllabus_topics || [])] })
      } else {
        const existing = unitMap.get(key)
        const existingTopicIds = new Set(existing.syllabus_topics.map(t => t.id || t.topic_name))
        for (const t of (u.syllabus_topics || [])) {
          if (!existingTopicIds.has(t.id || t.topic_name)) {
            existing.syllabus_topics.push(t)
            existingTopicIds.add(t.id || t.topic_name)
          }
        }
      }
    }
    return Array.from(unitMap.values())
  },

  async getUserProgress(userId) {
    const { data, error } = await supabase
      .from('user_syllabus_progress')
      .select('*')
      .eq('user_id', userId)
    if (error) throw error
    // Return as map: { topic_id -> progress }
    return Object.fromEntries((data ?? []).map(p => [p.topic_id, p]))
  },

  async upsertProgress(userId, topicId, status, score) {
    const { data, error } = await supabase
      .from('user_syllabus_progress')
      .upsert({ user_id: userId, topic_id: topicId, status, score, updated_at: new Date().toISOString() },
               { onConflict: 'user_id,topic_id' })
      .select().single()
    if (error) throw error
    return data
  },
}

// ─── Quick Recall ────────────────────────────────────────────────────────────
export const quickRecallService = {
  getTodayDateStr() {
    const d = new Date()
    return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`
  },

  /**
   * Check daily session status for this user:
   * Returns:
   * - status: 'COMPLETED_TODAY' (shows today's result, prevents generating second set)
   * - status: 'IN_PROGRESS' (resumes the same session)
   * - status: 'EXPIRED' (expired old in-progress session)
   * - status: 'NOT_STARTED' (generates fresh daily 5-question set)
   */
  async getDailyStatus(userId, examContext) {
    if (!userId) return { status: 'NOT_STARTED' }
    const todayStr = this.getTodayDateStr()
    const todayStart = `${todayStr}T00:00:00.000`

    const localKey = `qr_daily_${userId}_${todayStr}`
    let cached = null
    try {
      const item = localStorage.getItem(localKey)
      if (item) cached = JSON.parse(item)
    } catch (e) {}

    try {
      const { data: sessions } = await supabase
        .from('quick_recall_sessions')
        .select('*')
        .eq('user_id', userId)
        .gte('started_at', todayStart)
        .order('started_at', { ascending: false })
        .limit(1)

      const session = sessions?.[0]

      if (session) {
        const { data: answers } = await supabase
          .from('quick_recall_answers')
          .select('*')
          .eq('session_id', session.id)
          .order('question_index', { ascending: true })

        if (session.completed) {
          return {
            status: 'COMPLETED_TODAY',
            session,
            questions: session.questions_json || [],
            answers: answers || [],
            score: session.final_score ?? (answers || []).filter(a => a.is_correct).length,
            streakAtEnd: session.streak_at_end,
            points: session.recall_points,
          }
        }

        // Check if session started > 24 hours ago (expired)
        const ageMs = Date.now() - new Date(session.started_at).getTime()
        if (ageMs > 24 * 60 * 60 * 1000) {
          await supabase
            .from('quick_recall_sessions')
            .update({ completed: true, final_score: 0 })
            .eq('id', session.id)
          return { status: 'EXPIRED' }
        }

        return {
          status: 'IN_PROGRESS',
          session,
          questions: session.questions_json || [],
          answers: answers || [],
          resumeIndex: (answers || []).length,
        }
      }

      // Expire old hanging open sessions from past days
      const { data: oldOpen } = await supabase
        .from('quick_recall_sessions')
        .select('id')
        .eq('user_id', userId)
        .eq('completed', false)
        .lt('started_at', todayStart)
        .limit(5)

      if (oldOpen && oldOpen.length > 0) {
        await supabase
          .from('quick_recall_sessions')
          .update({ completed: true, final_score: 0 })
          .in('id', oldOpen.map(o => o.id))
      }
    } catch (err) {
      console.warn('[QuickRecall] DB check failed, using cache:', err)
      if (cached) {
        if (cached.completed) return { status: 'COMPLETED_TODAY', ...cached }
        return { status: 'IN_PROGRESS', ...cached }
      }
    }

    if (cached) {
      if (cached.completed) return { status: 'COMPLETED_TODAY', ...cached }
      return { status: 'IN_PROGRESS', ...cached }
    }

    return { status: 'NOT_STARTED' }
  },

  /**
   * Generates 5 personalized questions:
   * - Mix: ~50% PYQ + ~50% Synthetic (2-3 PYQ + 3-2 Synthetic)
   * - Personalization:
   *   1. Spaced Repetition: Previous wrong answers prioritized
   *   2. Long-unseen questions prioritized over recently seen
   *   3. Topic performance: weak topics given boost
   */
  async fetchPersonalizedRecallQuestions(userId, examContext) {
    const wrongTexts = new Set()
    const recentTexts = new Set()
    const weakTopics = new Set()

    if (userId) {
      try {
        const [wrongRes, recentRes, weakRes] = await Promise.allSettled([
          supabase
            .from('quick_recall_answers')
            .select('question_text')
            .eq('is_correct', false)
            .limit(50),
          supabase
            .from('quick_recall_answers')
            .select('question_text')
            .order('answered_at', { ascending: false })
            .limit(30),
          supabase
            .from('user_syllabus_progress')
            .select('topic_id, syllabus_topics(topic_name)')
            .eq('user_id', userId)
            .in('status', ['needs_revision', 'not_started'])
            .limit(10),
        ])

        if (wrongRes.status === 'fulfilled' && wrongRes.value.data) {
          wrongRes.value.data.forEach(w => {
            if (w.question_text) wrongTexts.add(w.question_text.trim().toLowerCase())
          })
        }
        if (recentRes.status === 'fulfilled' && recentRes.value.data) {
          recentRes.value.data.forEach(r => {
            if (r.question_text) recentTexts.add(r.question_text.trim().toLowerCase())
          })
        }
        if (weakRes.status === 'fulfilled' && weakRes.value.data) {
          weakRes.value.data.forEach(wt => {
            const name = wt.syllabus_topics?.topic_name
            if (name) weakTopics.add(name.toLowerCase())
          })
        }
      } catch (e) {
        console.warn('Personalization signals fetch fallback:', e)
      }
    }

    // 1. Fetch PYQ pool candidates
    let pyqCandidates = [...FALLBACK_PYQ_POOL]
    try {
      const { data: dbPyq } = await supabase
        .from('questions')
        .select('id, question_text, option_a, option_b, option_c, option_d, correct_option, explanation, papers!inner(title, is_pyq, exam_name)')
        .eq('papers.is_pyq', true)
        .not('correct_option', 'is', null)
        .limit(40)

      if (dbPyq && dbPyq.length > 0) {
        const formatted = dbPyq.map(q => ({
          id: q.id,
          question_text: q.question_text,
          option_a: q.option_a,
          option_b: q.option_b,
          option_c: q.option_c,
          option_d: q.option_d,
          correct_option: q.correct_option,
          explanation: q.explanation || 'Official Previous Year Question.',
          question_type: 'PYQ',
          is_pyq: true,
          exam_source: q.papers?.title || 'PYQ Archive',
        }))
        pyqCandidates = [...formatted, ...pyqCandidates]
      }
    } catch (e) {
      console.warn('DB PYQ query fallback:', e)
    }

    // 2. Fetch Synthetic/Model question candidates
    let synCandidates = [...FALLBACK_SYNTHETIC_POOL]
    try {
      const { data: dbSyn } = await supabase
        .from('recall_questions')
        .select('id, question_text, option_a, option_b, option_c, option_d, correct_option, explanation, subject')
        .eq('is_active', true)
        .limit(40)

      if (dbSyn && dbSyn.length > 0) {
        const formatted = dbSyn.map(q => ({
          id: q.id,
          question_text: q.question_text,
          option_a: q.option_a,
          option_b: q.option_b,
          option_c: q.option_c,
          option_d: q.option_d,
          correct_option: q.correct_option,
          explanation: q.explanation || 'Synthetic / Model Revision Question.',
          question_type: 'SYNTHETIC',
          is_pyq: false,
          subject: q.subject || 'General Knowledge',
        }))
        synCandidates = [...formatted, ...synCandidates]
      }
    } catch (e) {
      console.warn('DB Synthetic query fallback:', e)
    }

    // 3. Score candidates with personalization weighting
    const scoreCandidate = (q) => {
      let score = Math.random() * 10
      const txt = (q.question_text || '').trim().toLowerCase()

      // High priority for previous mistakes (Spaced repetition)
      if (wrongTexts.has(txt)) {
        score += 100
        q.is_previous_wrong = true
      }
      // Avoid recently answered
      if (recentTexts.has(txt)) {
        score -= 50
      } else {
        score += 25 // Long-unseen bonus
      }
      // Weak topic match bonus
      if (q.subject && weakTopics.has(q.subject.toLowerCase())) {
        score += 30
      }
      return score
    }

    pyqCandidates.sort((a, b) => scoreCandidate(b) - scoreCandidate(a))
    synCandidates.sort((a, b) => scoreCandidate(b) - scoreCandidate(a))

    const dedup = (list) => {
      const seen = new Set()
      return list.filter(item => {
        const key = item.question_text?.trim().toLowerCase()
        if (!key || seen.has(key)) return false
        seen.add(key)
        return true
      })
    }

    const uniquePyqs = dedup(pyqCandidates)
    const uniqueSyns = dedup(synCandidates)

    // Mix approximately 50% PYQ + 50% Synthetic (3 PYQ + 2 Synthetic OR 2 PYQ + 3 Synthetic)
    const pyqTargetCount = Math.random() > 0.5 ? 3 : 2
    const synTargetCount = 5 - pyqTargetCount

    let selectedPyqs = uniquePyqs.slice(0, pyqTargetCount)
    let selectedSyns = uniqueSyns.slice(0, synTargetCount)

    // Backfill if one pool doesn't have enough
    if (selectedPyqs.length < pyqTargetCount) {
      const deficit = pyqTargetCount - selectedPyqs.length
      selectedSyns = uniqueSyns.slice(0, synTargetCount + deficit)
    } else if (selectedSyns.length < synTargetCount) {
      const deficit = synTargetCount - selectedSyns.length
      selectedPyqs = uniquePyqs.slice(0, pyqTargetCount + deficit)
    }

    // Interleave to balance order
    const finalSet = []
    let pIdx = 0, sIdx = 0
    while (finalSet.length < 5 && (pIdx < selectedPyqs.length || sIdx < selectedSyns.length)) {
      if (pIdx < selectedPyqs.length) finalSet.push(selectedPyqs[pIdx++])
      if (finalSet.length < 5 && sIdx < selectedSyns.length) finalSet.push(selectedSyns[sIdx++])
    }

    return finalSet.slice(0, 5)
  },

  /** Backwards compatibility helper */
  async fetchRecallQuestions(examContext) {
    return this.fetchPersonalizedRecallQuestions(null, examContext)
  },

  async createSession(userId, examContext, questionsSnapshot) {
    const todayStr = this.getTodayDateStr()
    const sessionPayload = {
      user_id: userId,
      exam_context: examContext,
      questions_json: questionsSnapshot,
      completed: false,
      started_at: new Date().toISOString(),
    }

    let session = null
    try {
      const { data, error } = await supabase
        .from('quick_recall_sessions')
        .insert([sessionPayload])
        .select()
        .single()
      if (!error && data) session = data
    } catch (e) {
      console.warn('Local session created:', e)
    }

    if (!session) {
      session = {
        id: `qr-session-${Date.now()}`,
        ...sessionPayload,
      }
    }

    // Cache locally for resilient daily state
    try {
      localStorage.setItem(`qr_daily_${userId}_${todayStr}`, JSON.stringify({
        session,
        questions: questionsSnapshot,
        answers: [],
        completed: false,
      }))
    } catch (e) {}

    return session
  },

  async saveAnswer(sessionId, index, questionText, selected, correct, isCorrect, userId) {
    const todayStr = this.getTodayDateStr()
    const localKey = userId ? `qr_daily_${userId}_${todayStr}` : null

    if (localKey) {
      try {
        const item = localStorage.getItem(localKey)
        if (item) {
          const parsed = JSON.parse(item)
          parsed.answers = parsed.answers || []
          parsed.answers.push({
            question_index: index,
            question_text: questionText,
            selected_answer: selected,
            correct_answer: correct,
            is_correct: isCorrect,
          })
          localStorage.setItem(localKey, JSON.stringify(parsed))
        }
      } catch (e) {}
    }

    if (sessionId?.startsWith?.('qr-session-')) return { id: `ans-${Date.now()}` }

    try {
      const { data, error } = await supabase
        .from('quick_recall_answers')
        .insert([{
          session_id: sessionId,
          question_index: index,
          question_text: questionText,
          selected_answer: selected,
          correct_answer: correct,
          is_correct: isCorrect,
          answered_at: new Date().toISOString(),
        }])
        .select()
        .single()
      return data || {}
    } catch (e) {
      console.warn('saveAnswer error:', e)
      return {}
    }
  },

  /**
   * Finalise session with deterministic streak qualification:
   * - 5/5 correct: Qualifies streak -> streak increments by 1 day!
   * - 4/5 or below: Streak chain breaks -> streak resets to 0!
   */
  async finaliseSession(userId, correctCount, totalCount, sessionId) {
    const todayStr = this.getTodayDateStr()
    const isQualified = (correctCount === 5)

    let streakRow = null
    try {
      const { data } = await supabase
        .from('user_streaks')
        .select('*')
        .eq('user_id', userId)
        .maybeSingle()
      streakRow = data
    } catch (e) {
      console.warn('Error fetching streak row:', e)
    }

    const prevStreak = streakRow?.current_streak || 0
    const prevHighest = streakRow?.highest_streak || 0
    const prevPoints = streakRow?.recall_points || 0

    // 5/5 qualifies streak (+1). Anything less (<5, even 4/5) breaks streak chain (resets to 0).
    const newStreak = isQualified ? prevStreak + 1 : 0
    const highestStreak = Math.max(newStreak, prevHighest)
    const pointsEarned = correctCount * 10 + (isQualified ? 25 : 0) // Bonus 25 points for perfect 5/5
    const totalPoints = prevPoints + pointsEarned

    try {
      await supabase.from('user_streaks').upsert({
        user_id: userId,
        current_streak: newStreak,
        highest_streak: highestStreak,
        recall_points: totalPoints,
        questions_answered: (streakRow?.questions_answered || 0) + totalCount,
        daily_recall_done: true,
        last_recall_date: todayStr,
        updated_at: new Date().toISOString(),
      }, { onConflict: 'user_id' })
    } catch (e) {
      console.warn('Error updating user_streaks:', e)
    }

    if (sessionId && !sessionId.startsWith('qr-session-')) {
      try {
        await supabase
          .from('quick_recall_sessions')
          .update({
            completed: true,
            final_score: correctCount,
            streak_at_end: newStreak,
            recall_points: pointsEarned,
            completed_at: new Date().toISOString(),
          })
          .eq('id', sessionId)
      } catch (e) {
        console.warn('Error completing session in DB:', e)
      }
    }

    try {
      const localKey = `qr_daily_${userId}_${todayStr}`
      const item = localStorage.getItem(localKey)
      if (item) {
        const parsed = JSON.parse(item)
        parsed.completed = true
        parsed.final_score = correctCount
        parsed.streak_at_end = newStreak
        parsed.qualified = isQualified
        localStorage.setItem(localKey, JSON.stringify(parsed))
      }
    } catch (e) {}

    return {
      new_streak: newStreak,
      prev_streak: prevStreak,
      highest_streak: highestStreak,
      qualified: isQualified,
      score: correctCount,
      total: totalCount,
      recall_points: pointsEarned,
      total_points: totalPoints,
    }
  },
}

