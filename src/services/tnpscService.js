// ─── Analytics ────────────────────────────────────────────────────────────────
export const analyticsService = {
  /** Compute analytics from completed attempts, optionally filtered by exam. */
  async getOverview(userId, examName = null) {
    let q = supabase
      .from('attempts')
      .select('*, papers(title, subject, exam_name), attempt_answers(*, questions(question_text, correct_option))')
      .eq('user_id', userId)
      .eq('status', 'completed')
      .order('submitted_at', { ascending: false })
      .limit(50)

    const { data: attempts, error } = await q
    if (error) throw error

    // Filter client-side by exam name so we don't lose the joined data
    const list = (attempts ?? []).filter(a =>
      !examName || a.papers?.exam_name === examName
    )

    if (list.length === 0) return { hasData: false }

    const totalAttempts  = list.length
    const totalQuestions = list.reduce((s, a) => s + (a.correct_count + a.incorrect_count + a.unanswered_count), 0)
    const totalCorrect   = list.reduce((s, a) => s + (a.correct_count   ?? 0), 0)
    const totalWrong     = list.reduce((s, a) => s + (a.incorrect_count ?? 0), 0)
    const totalSkipped   = list.reduce((s, a) => s + (a.unanswered_count ?? 0), 0)
    const avgScore       = list.reduce((s, a) => s + Number(a.score     ?? 0), 0) / totalAttempts
    const avgAccuracy    = list.reduce((s, a) => s + Number(a.accuracy  ?? 0), 0) / totalAttempts

    // Subject breakdown
    const subjectMap = {}
    list.forEach(a => {
      const subj = a.papers?.subject ?? 'General'
      if (!subjectMap[subj]) subjectMap[subj] = { correct: 0, total: 0, count: 0 }
      subjectMap[subj].correct += a.correct_count ?? 0
      subjectMap[subj].total   += (a.correct_count + a.incorrect_count + a.unanswered_count)
      subjectMap[subj].count   += 1
    })
    const subjectBreakdown = Object.entries(subjectMap).map(([subject, v]) => ({
      subject,
      accuracy:  v.total ? ((v.correct / v.total) * 100).toFixed(1) : '0',
      attempted: v.total,
      correct:   v.correct,
      count:     v.count,
    }))

    // Recent trend (last 8 attempts)
    const trend = list.slice(0, 8).reverse().map((a, i) => ({
      attempt: i + 1,
      score:    Number(a.score    ?? 0).toFixed(1),
      accuracy: Number(a.accuracy ?? 0).toFixed(1),
      date:     a.submitted_at,
    }))

    return {
      hasData: true,
      totalAttempts,
      totalQuestions,
      totalCorrect,
      totalWrong,
      totalSkipped,
      avgScore:    avgScore.toFixed(2),
      avgAccuracy: avgAccuracy.toFixed(1),
      subjectBreakdown,
      trend,
      recentAttempts: list.slice(0, 5),
    }
  },

  /** Compute separate QUICK_RECALL category metrics */
  async getQuickRecallAnalytics(userId) {
    try {
      const [sessionsRes, streakRes] = await Promise.allSettled([
        supabase
          .from('quick_recall_sessions')
          .select('*, quick_recall_answers(*)')
          .eq('user_id', userId)
          .eq('completed', true)
          .order('started_at', { ascending: false }),
        supabase
          .from('user_streaks')
          .select('*')
          .eq('user_id', userId)
          .maybeSingle(),
      ])

      const sessions = sessionsRes.status === 'fulfilled' ? sessionsRes.value.data ?? [] : []
      const streak = streakRes.status === 'fulfilled' ? streakRes.value.data : null

      const totalSessions = sessions.length
      const perfectSessions = sessions.filter(s => Number(s.final_score) === 5).length
      const qualifyRate = totalSessions > 0 ? ((perfectSessions / totalSessions) * 100).toFixed(1) : '0'

      let pyqCorrect = 0, pyqTotal = 0
      let synCorrect = 0, synTotal = 0

      sessions.forEach(s => {
        const answers = s.quick_recall_answers || []
        const qs = s.questions_json || []
        answers.forEach(a => {
          const q = qs[a.question_index]
          const isPyq = q?.question_type === 'PYQ' || q?.is_pyq
          if (isPyq) {
            pyqTotal++
            if (a.is_correct) pyqCorrect++
          } else {
            synTotal++
            if (a.is_correct) synCorrect++
          }
        })
      })

      const pyqAccuracy = pyqTotal > 0 ? ((pyqCorrect / pyqTotal) * 100).toFixed(1) : '—'
      const synAccuracy = synTotal > 0 ? ((synCorrect / synTotal) * 100).toFixed(1) : '—'

      return {
        hasData: totalSessions > 0 || (streak?.questions_answered > 0),
        category: 'QUICK_RECALL',
        totalSessions,
        perfectSessions,
        qualifyRate,
        currentStreak: streak?.current_streak ?? 0,
        highestStreak: streak?.highest_streak ?? 0,
        recallPoints: streak?.recall_points ?? 0,
        questionsAnswered: streak?.questions_answered ?? (totalSessions * 5),
        pyqAccuracy,
        synAccuracy,
        recentSessions: sessions.slice(0, 7),
      }
    } catch (e) {
      console.warn('getQuickRecallAnalytics error:', e)
      return { hasData: false, category: 'QUICK_RECALL' }
    }
  },
}

