export const profileService = {
  async update(userId, payload) {
    const { data, error } = await supabase
      .from('profiles')
      .update({ ...payload, updated_at: new Date().toISOString() })
      .eq('id', userId)
      .select().single()
    if (error) throw error
    return data
  },
}
